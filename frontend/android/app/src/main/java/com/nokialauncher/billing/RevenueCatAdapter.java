package com.nokialauncher.billing;

import android.content.Context;
import android.app.Activity;
import android.os.Looper;
import com.revenuecat.purchases.PurchaseParams;
import com.revenuecat.purchases.PurchasesError;
import com.revenuecat.purchases.PurchasesErrorCode;
import com.revenuecat.purchases.interfaces.PurchaseCallback;
import com.revenuecat.purchases.CacheFetchPolicy;
import com.revenuecat.purchases.EntitlementVerificationMode;
import com.revenuecat.purchases.LogLevel;
import com.revenuecat.purchases.Purchases;
import com.revenuecat.purchases.PurchasesConfiguration;
import com.revenuecat.purchases.interfaces.ReceiveCustomerInfoCallback;
import com.revenuecat.purchases.interfaces.GetStoreProductsCallback;
import com.revenuecat.purchases.interfaces.ReceiveOfferingsCallback;
import com.revenuecat.purchases.interfaces.UpdatedCustomerInfoListener;
import java.util.List;
import java.util.Objects;

/**
 * Process-owned SDK boundary, never Activity-owned. Raw SDK data remains native.
 * The controller must normalize verification and serialize callback application.
 * This adapter does not grant rights and does not launch a purchase by itself.
 */
public final class RevenueCatAdapter {
    private static RevenueCatAdapter shared;
    private final Purchases purchases;
    private final BillingProviderConfig identity;

    private RevenueCatAdapter(Context context, BillingProviderConfig config) {
        if (!config.isConfigured()) throw new IllegalStateException("billing_not_configured");
        if (Purchases.isConfigured()) throw new IllegalStateException("billing_owner_already_configured");
        // Anonymous identity is generated by the SDK; no email/login/account mapping.
        Purchases.setLogLevel(LogLevel.ERROR);
        Purchases.configure(new PurchasesConfiguration.Builder(context.getApplicationContext(), config.publicKey)
                .entitlementVerificationMode(EntitlementVerificationMode.INFORMATIONAL)
                .automaticDeviceIdentifierCollectionEnabled(false)
                .diagnosticsEnabled(false)
                .showInAppMessagesAutomatically(false)
                .build());
        purchases = Purchases.getSharedInstance();
        identity = config;
    }

    public static synchronized RevenueCatAdapter initialize(Context context, BillingProviderConfig config) {
        if (shared == null) shared = new RevenueCatAdapter(context, config);
        else if (!shared.identity.hasSameIdentity(config))
            throw new IllegalStateException("billing_configuration_changed_in_process");
        return shared;
    }

    /** Listener is a notification, not an instruction to recursively fetch again. */
    public void setCustomerInfoListener(UpdatedCustomerInfoListener listener) {
        purchases.setUpdatedCustomerInfoListener(listener);
    }

    /** FETCH_CURRENT expresses request intent, not proof of server provenance. */
    public void fetchCurrent(ReceiveCustomerInfoCallback callback) {
        purchases.getCustomerInfo(CacheFetchPolicy.FETCH_CURRENT, callback);
    }

    public void fetchOfferings(ReceiveOfferingsCallback callback) {
        purchases.getOfferings(callback);
    }

    /** Direct public SDK Play product query; does not reuse the Offerings cache. */
    public void getProducts(List<String> configuredProductIds, GetStoreProductsCallback callback) {
        purchases.getProducts(configuredProductIds, callback);
    }

    /** Native foreground host only, after serialized checks and durable journal write.
     * Host must prove RESUMED/generation and consume a fresh preflight selection; Activity
     * liveness here is a final defensive check, not foreground authorization. No call site yet.
     */
    void purchase(Activity activity, RevenueCatCatalog.Selection selection, PurchaseCallback callback) {
        Objects.requireNonNull(activity); Objects.requireNonNull(selection); Objects.requireNonNull(callback);
        if (Looper.myLooper() != Looper.getMainLooper() || activity.isFinishing() || activity.isDestroyed())
            throw new IllegalStateException("billing_host_unavailable");
        boolean lifetime = selection.plan == BillingSnapshot.Plan.LIFETIME;
        String product = lifetime ? identity.lifetimeProduct : identity.subscriptionProduct;
        String base = lifetime ? null : selection.plan == BillingSnapshot.Plan.MONTHLY
                ? identity.monthlyPlan : identity.yearlyPlan;
        if (!product.equals(selection.productId) || !Objects.equals(base, selection.basePlanId)
                || !identity.offering.equals(selection.sdkPackage.getPresentedOfferingContext().getOfferingIdentifier()))
            throw new IllegalArgumentException("billing_selection_mismatch");
        PurchaseParams.Builder builder;
        if (lifetime) {
            if (selection.oneTimeOption == null || selection.option != null)
                throw new IllegalArgumentException("billing_invalid_lifetime_option");
            builder = new PurchaseParams.Builder(activity, selection.product);
        } else {
            if (selection.option == null || selection.option.getOfferId() != null
                    || !base.equals(selection.option.getBasePlanId()))
                throw new IllegalArgumentException("billing_invalid_subscription_option");
            // Package/StoreProduct would allow SDK defaultOption to select a trial.
            builder = new PurchaseParams.Builder(activity, selection.option);
        }
        purchases.purchase(builder.build(), callback);
    }

    /** Error only; never treats SDK success or already-owned errors as verified rights.
     * Inconsistent cancellation signals stay uncertain and require receipt reconciliation.
     */
    static BillingController.PurchaseOutcome classifyPurchaseError(PurchasesError error, boolean userCancelled) {
        if (error != null && error.getCode() == PurchasesErrorCode.PurchaseCancelledError && userCancelled)
            return BillingController.PurchaseOutcome.CANCELED;
        if (error != null && error.getCode() == PurchasesErrorCode.PaymentPendingError && !userCancelled)
            return BillingController.PurchaseOutcome.PENDING;
        if (error != null && error.getCode() == PurchasesErrorCode.ProductNotAvailableForPurchaseError && !userCancelled)
            return BillingController.PurchaseOutcome.PRODUCT_UNAVAILABLE;
        return BillingController.PurchaseOutcome.UNCERTAIN;
    }

    /** Local acceptance diagnostics only. Never include SDK text, account IDs,
     * receipt/order IDs, offer tokens or credentials, and never emit in production. */
    static String acceptanceErrorDiagnostic(String buildType, PurchasesError error, boolean userCancelled) {
        if (!"internalBilling".equals(buildType)) return null;
        return "checkout_error_code=" + (error == null ? "missing" : error.getCode().name())
                + ";user_cancelled=" + userCancelled;
    }

    /** Invoke only after explicit Restore input; controller owns lock and journal. */
    public void restoreFromUserAction(ReceiveCustomerInfoCallback callback) {
        purchases.restorePurchases(callback);
    }

    /** User-triggered support summary only; never emit automatically in logs/events. */
    public String getSupportId() { return purchases.getAppUserID(); }
}
