export const CONTROL_SURFACE_MODES = Object.freeze({
  NAVIGATION: "NAVIGATION",
  INPUT_TEXT: "INPUT_TEXT",
  INPUT_NUMBER: "INPUT_NUMBER",
  IMMERSIVE: "IMMERSIVE",
  SECURE: "SECURE",
  UNSUPPORTED: "UNSUPPORTED",
  HIDDEN: "HIDDEN",
});

export const CONTROL_SURFACE_EVENTS = Object.freeze({
  TEXT_FOCUSED: "TEXT_FOCUSED",
  NUMBER_FOCUSED: "NUMBER_FOCUSED",
  SECURE_FOCUSED: "SECURE_FOCUSED",
  INPUT_FINISHED: "INPUT_FINISHED",
  LANDSCAPE_ENTERED: "LANDSCAPE_ENTERED",
  UNSUPPORTED_WINDOW: "UNSUPPORTED_WINDOW",
  SERVICE_DISABLED: "SERVICE_DISABLED",
});

const EVENT_TARGETS = Object.freeze({
  TEXT_FOCUSED: "INPUT_TEXT",
  NUMBER_FOCUSED: "INPUT_NUMBER",
  SECURE_FOCUSED: "SECURE",
  LANDSCAPE_ENTERED: "IMMERSIVE",
  UNSUPPORTED_WINDOW: "UNSUPPORTED",
  SERVICE_DISABLED: "HIDDEN",
});

export const reduceControlSurface = (mode, event) => {
  if (event === CONTROL_SURFACE_EVENTS.INPUT_FINISHED) {
    return mode === CONTROL_SURFACE_MODES.HIDDEN
      ? CONTROL_SURFACE_MODES.HIDDEN
      : CONTROL_SURFACE_MODES.NAVIGATION;
  }

  return EVENT_TARGETS[event] || mode;
};
